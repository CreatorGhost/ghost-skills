#!/usr/bin/env python3
"""Lay per-sentence voice clips on one track and write word timings.

usage: layout.py SCRIPT.txt CLIPS_DIR ASSETS_DIR [--tempo 1.15] [--gap 0.2] [--gaps '{"1":0.5,"5":0.55}']
  CLIPS_DIR holds s01.wav, s02.wav ... (one per script line, from vo.sh or any voice)
out: ASSETS_DIR/vo.wav and ASSETS_DIR/timing.js  ->  window.VO = {S:[sentence starts], E:[ends], W:[[[word, t], ...], ...]}
Needs ffmpeg + whisper-cli (whisper.cpp); the ggml model comes from --model or $WHISPER_MODEL.
"""
import argparse, json, os, re, subprocess, tempfile
ap = argparse.ArgumentParser(); ap.add_argument("script"); ap.add_argument("clips"); ap.add_argument("assets")
ap.add_argument("--model", default=os.environ.get("WHISPER_MODEL")); ap.add_argument("--tempo", type=float, default=1.15); ap.add_argument("--gap", type=float, default=0.2); ap.add_argument("--gaps", default="{}")
a = ap.parse_args()
import glob
MODEL = a.model or next(iter(sorted(glob.glob(os.path.expanduser("~/Library/Application Support/*/models/ggml-*.bin")) + glob.glob(os.path.expanduser("~/.cache/whisper*/ggml-*.bin")))), None)
if not MODEL or not os.path.exists(MODEL):
    raise SystemExit("no whisper.cpp model: pass --model PATH or set WHISPER_MODEL (a ggml-*.bin, e.g. ggml-large-v3-turbo.bin)")
GAP = {int(k): v for k, v in json.loads(a.gaps).items()}   # pause AFTER sentence n; give hero beats room (0.4-0.6)
lines = [l.strip() for l in open(a.script) if l.strip()]
tmp = tempfile.mkdtemp(); t = 0.12; S, E, W, ins, filt = [], [], [], [], []
for i, line in enumerate(lines, 1):
    src, dst = f"{a.clips}/s{i:02d}.wav", f"{tmp}/s{i:02d}.wav"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src, "-af", f"atempo={a.tempo}", dst], check=True)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", dst, "-ar", "16000", "-ac", "1", f"{tmp}/w.wav"], check=True)
    subprocess.run(["whisper-cli", "-m", MODEL, "-f", f"{tmp}/w.wav", "-ml", "1", "-sow", "-oj", "-of", f"{tmp}/w"], check=True, capture_output=True)
    d = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", dst]))
    ws = [[s["text"].strip(), round(t + s["offsets"]["from"] / 1000, 2)] for s in json.load(open(f"{tmp}/w.json"))["transcription"] if re.search(r"\w", s["text"])]
    S.append(round(t, 2)); E.append(round(t + d, 2)); W.append(ws)
    ins += ["-i", dst]; filt.append(f"[{i-1}:a]adelay={int(t*1000)}:all=1[a{i}]")
    print(f"{i:02d} {t:6.2f}-{t+d:6.2f}  " + " ".join(f"{w}@{x}" for w, x in ws))   # check word counts against the script here
    t += d + GAP.get(i, a.gap)
mix = ";".join(filt) + ";" + "".join(f"[a{i}]" for i in range(1, len(lines) + 1)) + f"amix=inputs={len(lines)}:normalize=0,highpass=f=80,acompressor=threshold=-18dB:ratio=3:attack=5:release=120,loudnorm=I=-15:TP=-1.5:LRA=11[o]"
subprocess.run(["ffmpeg", "-v", "error", "-y", *ins, "-filter_complex", mix, "-map", "[o]", "-ar", "48000", "-ac", "2", f"{a.assets}/vo.wav"], check=True)
open(f"{a.assets}/timing.js", "w").write("// generated by open-katana/scripts/layout.py; seconds from the start of the film\nwindow.VO = " + json.dumps({"S": S, "E": E, "W": W}) + ";\n")
print("end", round(t, 2), "-> set the root data-duration to this + a 1.5-2 s hold")
